class Solution {
public:
    int minMovesToSeat(vector<int>& seats, vector<int>& students) {
        sort(seats.begin(), seats.end());
        sort(students.begin(), students.end());
        int total_moves = 0;
        int n = seats.size();
        for (int i = 0; i < n; ++i) {
            total_moves += abs(seats[i] - students[i]);
        }
        return total_moves;
    }
};
