bool is_prime(int n) {
    if (n < 2) return false;
    for (int i = 2; i * i <= n; i++) {
        if (n % i == 0) return false;
    }
    return true;
}

int next_prime(int x) {
    while (!is_prime(x)) {
        x++;
    }
    return x;
}

void solve() {
    int d;
    cin >> d;

    int p = next_prime(1 + d);
    int q = next_prime(p + d);

    cout << min(p * q, p * p * p) << endl;
}

signed main() {
    fastio();
    int t;
    cin >> t;
    while (t--) {
        solve();
    }
    return 0;
}
